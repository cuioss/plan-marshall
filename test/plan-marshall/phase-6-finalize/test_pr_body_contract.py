"""PR-body, squash-message, and plan-commit-trailer contracts for deliverable 5.

Truthfulness fixes plus PR-body and squash-message repairs, pinned from the
test side:

* **Full PR body (no footer, single Intent, no comment).** The template carries
  no ``Generated by`` footer, exactly one ``## Intent`` heading at its position,
  and no ``<!-- -->`` authoring note — and a body rendered through the real
  ``pr_intent_section`` renderer keeps that shape: the Intent slot is filled in
  place, never appended as a second section.
* **Squash message (title plus Summary plus one trailer).** The merge commit
  message is composed explicitly from the PR title, the plan's own
  ``## Summary`` section body, and exactly the project trailer. A body carrying
  a review-bot summary (e.g. a ``Summary by CodeRabbit`` section) and a foreign
  trailer contributes neither: the bot prose is dropped and no second trailer
  lands on the base branch.
* **Plan commit path (repair, not refusal).** A bare subject committed through
  the plan path reads back with the project trailer appended
  (``ensure_project_trailer``); an already-trailered message is returned
  unchanged, so a second append never doubles the trailer. A missing trailer is
  an authoring omission the path repairs, not a verdict a pre-push gate blocks
  on.
"""

from __future__ import annotations

import re
from pathlib import Path
from unittest.mock import patch

from conftest import PROJECT_ROOT, load_script_module

pis = load_script_module('plan-marshall', 'phase-6-finalize', 'pr_intent_section.py')
git_workflow = load_script_module('plan-marshall', 'workflow-integration-git', 'git-workflow.py', 'git_workflow')

_TEMPLATE_REL = 'marketplace/bundles/plan-marshall/skills/phase-6-finalize/templates/pr-template.md'
_BRANCH_CLEANUP_REL = 'marketplace/bundles/plan-marshall/skills/phase-6-finalize/standards/branch-cleanup.md'
_GIT_WORKFLOW_REL = 'marketplace/bundles/plan-marshall/skills/workflow-integration-git/scripts/git-workflow.py'

_PROJECT_TRAILER = 'Co-Authored-By: plan-marshall <noreply@cuioss.de>'

_INTENT_DRAFT = (
    'The merge workflow reused the PR page body as the squash message. '
    'The message is now composed explicitly from the title, the plan Summary, and one trailer. '
    'Bot summaries and foreign trailers are deliberately excluded.'
)


def _template_text() -> str:
    """Read the PR template from the worktree under test."""
    path: Path = PROJECT_ROOT / _TEMPLATE_REL
    text: str = path.read_text(encoding='utf-8')
    return text


def _heading_count(body: str, heading: str) -> int:
    """Count exact ``## {heading}`` heading lines in a markdown body."""
    return len(re.findall(rf'^## {re.escape(heading)}[ \t]*$', body, re.MULTILINE))


class _Completed:
    """Minimal ``subprocess.run`` result stand-in."""

    def __init__(self, stdout: str = '', returncode: int = 0) -> None:
        self.stdout = stdout
        self.returncode = returncode
        self.stderr = ''


def _outline_toon(content: str) -> str:
    return f'status: success\nplan_id: p\nsection: summary\ncontent: "{content}"\n'


def _render_full_body(tmp_path: Path) -> str:
    """Render the template through the real Intent renderer and return the body."""
    template = _template_text()
    body_path = tmp_path / 'pr-body.md'
    body_path.write_text(
        template.replace('{summary_from_task_md}', 'Repair the squash message composition.')
        .replace('{list_of_changes}', '- Compose the message explicitly.')
        .replace('{verification_command}', 'test-compile plan-marshall')
        .replace('{closes_issue_if_present}', ''),
        encoding='utf-8',
    )
    draft_path = tmp_path / 'intent-draft.md'
    draft_path.write_text(_INTENT_DRAFT, encoding='utf-8')
    import argparse

    args = argparse.Namespace(plan_id='pr-body-contract', draft_path=str(draft_path), body_path=str(body_path))
    with patch.object(pis.subprocess, 'run', return_value=_Completed(_outline_toon('Squash repair intent'))):
        code = pis.cmd_render(args)
    assert code == 0
    return body_path.read_text(encoding='utf-8')


# =============================================================================
# Full PR body — no footer, single Intent, no comment
# =============================================================================


class TestFullPrBody:
    """The rendered body carries exactly the template's sections and nothing else."""

    def test_template_has_no_footer_single_intent_and_no_comment(self) -> None:
        """The template itself states the contract the renderer must preserve."""
        template = _template_text()
        assert 'Generated by' not in template
        assert _heading_count(template, 'Intent') == 1
        assert '<!--' not in template

    def test_rendered_body_has_no_footer_single_intent_and_no_comment(self, tmp_path: Path) -> None:
        """A full render fills the Intent slot in place and appends nothing else."""
        body = _render_full_body(tmp_path)
        assert 'Generated by' not in body
        assert _heading_count(body, 'Intent') == 1
        assert '<!--' not in body
        assert 'The merge workflow reused the PR page body' in body

    def test_second_render_keeps_a_single_intent(self, tmp_path: Path) -> None:
        """Re-rendering a rendered body replaces the slot — never a second section."""
        template = _template_text()
        body_path = tmp_path / 'pr-body-rerender.md'
        body_path.write_text(template, encoding='utf-8')
        draft_path = tmp_path / 'intent-draft-rerender.md'
        draft_path.write_text(_INTENT_DRAFT, encoding='utf-8')
        import argparse

        args = argparse.Namespace(plan_id='pr-body-contract', draft_path=str(draft_path), body_path=str(body_path))
        with patch.object(pis.subprocess, 'run', return_value=_Completed(_outline_toon('Squash repair intent'))):
            assert pis.cmd_render(args) == 0
            assert pis.cmd_render(args) == 0
        body = body_path.read_text(encoding='utf-8')
        assert _heading_count(body, 'Intent') == 1


