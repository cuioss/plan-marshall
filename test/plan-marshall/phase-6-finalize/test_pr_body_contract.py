# Squash message — title plus Summary plus one trailer
# =============================================================================


def _summary_section(body: str) -> str:
    """Return the plan's own ``## Summary`` section body (up to the next heading)."""
    match = re.search(r'^## Summary[ \t]*\n(.*?)(?=^## |\Z)', body, re.MULTILINE | re.DOTALL)
    assert match is not None, 'the PR body carries no ## Summary section'
    return match.group(1).strip()


def _compose_squash_message(title: str, body: str, trailer: str) -> str:
    """Compose the squash message per the branch-cleanup three-part rule.

    Exactly the documented shape: the PR title line, the plan's own
    ``## Summary`` section body (never a review-bot summary appended after
    creation), and exactly the project trailer — one trailer, never two.
    """
    return f'{title.strip()}\n\n{_summary_section(body)}\n\n{trailer.strip()}\n'


class TestSquashMessage:
    """The documented three-part rule, pinned on text and on a bot-carrying body."""

    def test_branch_cleanup_states_the_three_part_rule(self) -> None:
        """The merge path composes explicitly — never the page body, one trailer."""
        doc = (PROJECT_ROOT / _BRANCH_CLEANUP_REL).read_text(encoding='utf-8')
        assert 'The merge commit message is composed explicitly — never the PR page body.' in doc
        assert 'one trailer, never two' in doc

    def test_bot_summary_and_second_trailer_do_not_land(self, tmp_path: Path) -> None:
        """A bot summary and a foreign trailer on the body stay off the message."""
        body = _render_full_body(tmp_path)
        body_with_bot = (
            body + '\n## Summary by CodeRabbit\n\nBot prose about the diff.\n'
            '\nCo-Authored-By: foreign-bot <bot@example.com>\n'
        )
        message = _compose_squash_message(
            'fix(execute-loop): repair squash message composition', body_with_bot, _PROJECT_TRAILER
        )
        assert message.splitlines()[0] == 'fix(execute-loop): repair squash message composition'
        assert 'Repair the squash message composition.' in message
        assert 'Bot prose about the diff.' not in message
        assert 'Summary by CodeRabbit' not in message
        assert 'foreign-bot' not in message
        assert message.count(_PROJECT_TRAILER) == 1
        assert message.count('Co-Authored-By:') == 1


# =============================================================================
# Plan commit path — the trailer is appended, never refused
# =============================================================================


class TestPlanCommitTrailer:
    """A bare subject reads back trailered; a trailered message is untouched."""

    def test_source_states_repair_not_refusal(self) -> None:
        """The plan commit path appends a missing trailer instead of refusing it."""
        source = (PROJECT_ROOT / _GIT_WORKFLOW_REL).read_text(encoding='utf-8')
        assert 'rather than refusing a trailerless commit at a pre-push' in source

    def test_bare_subject_gains_the_trailer(self) -> None:
        """Committing a bare subject through the plan path reads back trailered."""
        message = git_workflow.ensure_project_trailer('fix(scope): repair the message', _PROJECT_TRAILER)
        assert message.count(_PROJECT_TRAILER) == 1
        assert message.splitlines()[0] == 'fix(scope): repair the message'

    def test_trailered_message_is_returned_unchanged(self) -> None:
        """A message already carrying the trailer is never doubled."""
        original = f'fix(scope): repair the message\n\n{_PROJECT_TRAILER}\n'
        assert git_workflow.ensure_project_trailer(original, _PROJECT_TRAILER) == original

    def test_trailing_blank_lines_still_yield_a_single_trailer(self) -> None:
        """Trailing whitespace does not defeat the trailing-line match."""
        message = git_workflow.ensure_project_trailer('fix(scope): repair the message\n\n', _PROJECT_TRAILER)
        assert message.count(_PROJECT_TRAILER) == 1
